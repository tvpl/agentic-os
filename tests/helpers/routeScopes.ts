/** The routes that need no credential (`config.public`): not in the table above. */
export const PUBLIC_ROUTES: readonly string[] = ["GET /api/meta", "POST /api/pair/claim"];

export function routesOf(scope: RouteScope): string[] {
  return Object.entries(EXPECTED_ROUTE_SCOPES)
    .filter(([, s]) => s === scope)
    .map(([route]) => route);
}
